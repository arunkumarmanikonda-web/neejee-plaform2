// Save a fal-hosted image to our Supabase storage + Asset row.
// POST body: { url, alt?, caption?, tags? }
import { NextResponse } from 'next/server';
import { prisma } from '@/lib/prisma';
import { getSession } from '@/lib/auth';
import { canDraftMarketing } from '@/lib/marketing/roles';
import { getStorageOrigin, PUBLIC_STORAGE_BUCKET, uploadFile, makeUploadPath, storageConfigured } from '@/lib/storage';

export const dynamic = 'force-dynamic';
export const runtime = 'nodejs';
export const maxDuration = 60;

export async function POST(req: Request) {
  const session = await getSession();
  if (!canDraftMarketing(session)) {
    return NextResponse.json({ error: 'Forbidden' }, { status: 403 });
  }
  if (!storageConfigured()) {
    return NextResponse.json({ error: 'Storage not configured' }, { status: 503 });
  }

  try {
    const { url, alt, caption, tags } = await req.json();
    if (!url) return NextResponse.json({ error: 'url required' }, { status: 400 });

    const source = new URL(url);
    const alreadyStored = source.origin === getStorageOrigin() && source.pathname.startsWith('/storage/v1/object/public/' + encodeURIComponent(PUBLIC_STORAGE_BUCKET) + '/marketing-studio/');
    const providerImage = source.hostname === 'fal.media' || source.hostname.endsWith('.fal.media');
    if (source.protocol !== 'https:' || source.username || source.password || (!alreadyStored && !providerImage)) {
      return NextResponse.json({ error: 'Choose an image generated by Marketing Studio.' }, { status: 400 });
    }
    const resp = await fetch(source, { redirect: 'error', signal: AbortSignal.timeout(30000) });
    if (!resp.ok) throw new Error(`Failed to fetch source image: ${resp.status}`);
    const contentType = resp.headers.get('content-type')?.split(';')[0] || '';
    if (!['image/png', 'image/jpeg', 'image/webp'].includes(contentType)) return NextResponse.json({ error: 'Invalid image' }, { status: 400 });
    const buf = Buffer.from(await resp.arrayBuffer());
    if (!buf.length || buf.length > 16 * 1024 * 1024) return NextResponse.json({ error: 'Invalid image size' }, { status: 400 });
    const ext = contentType.includes('png') ? 'png' : contentType.includes('webp') ? 'webp' : 'jpg';
    const filename = `studio-${Date.now()}.${ext}`;

    const path = makeUploadPath('marketing-studio', filename);
    const storedUrl = alreadyStored ? source.href : (await uploadFile(path, buf, contentType)).url;

    const asset = await prisma.asset.create({
      data: {
        url: storedUrl,
        filename,
        folder: 'marketing-studio',
        size: buf.length,
        contentType,
        alt: alt || null,
        caption: caption || null,
        tags: Array.isArray(tags) ? tags : [],
        uploadedBy: session!.id,
      },
    });

    return NextResponse.json({ asset });
  } catch (err: any) {
    console.error('[marketing-studio.save-asset]', err);
    return NextResponse.json({ error: err?.message || 'Save failed' }, { status: 500 });
  }
}
